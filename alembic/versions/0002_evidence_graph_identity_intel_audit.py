def _slug(text: str) -> str:
    return re.sub(r"[^a-z0-9]+", "-", text.lower()).strip("-")[:120]


def _fingerprint(key, port, protocol, cve, service, version, title) -> str:
    """Frozen copy of app.services.fingerprint.fingerprint (migrations must not import app code that may change).

    Caveat: v1 used `service_name or <canonical product>` for CVE-less findings; the canonical product is not
    stored, so a CVE-less finding without a service name can be re-created once on the next scan.
    """
    base = [key, str(port or 0), (protocol or "tcp").lower()]
    parts = base + ["cve", cve.upper()] if cve else base + ["finding", service or "", version or "", _slug(title)]
    return hashlib.sha256("|".join(parts).encode()).hexdigest()


def _refingerprint(by_ip: bool) -> None:
    """Re-key every finding: v1 keyed on the IP address, v2 keys on the internal asset id."""
    conn = op.get_bind()
    rows = conn.execute(
        sa.text(
            "SELECT v.id, v.asset_id, a.ip_address, v.port, v.protocol, v.cve_id, v.service_name, v.version, v.title "
            "FROM vulnerabilities v JOIN assets a ON a.id = v.asset_id"
        )
    ).fetchall()
    for vid, asset_id, ip, port, proto, cve, service, version, title in rows:
        fp = _fingerprint(ip if by_ip else str(asset_id), port, proto, cve, service, version, title)
        conn.execute(sa.text("UPDATE vulnerabilities SET fingerprint = :fp WHERE id = :id"), {"fp": fp, "id": vid})


